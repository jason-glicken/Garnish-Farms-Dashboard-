-- Garnish Farms: relational harvest history table
-- REVIEW ONLY. This migration is NOT executed by the dashboard ZIP build.
-- Designed against the verified public.batches schema (id bigint primary key).
-- Owner UUID matches current owner-only policies on batches, batch_items, cultures.

begin;

create table if not exists public.harvests (
  id bigint generated by default as identity primary key,
  batch_pk bigint references public.batches(id) on delete set null,
  batch_id text not null, -- human-readable batch label retained for display/history
  strain text not null,
  harvest_date date not null,
  flush_number integer not null default 1 check (flush_number > 0),
  weight_lbs numeric(10,2) not null default 0 check (weight_lbs >= 0),
  notes text,
  created_at timestamptz not null default timezone('utc'::text, now())
);

-- Safe additive path if an earlier draft table was created without batch_pk.
alter table public.harvests
  add column if not exists batch_pk bigint references public.batches(id) on delete set null;

create index if not exists harvests_batch_pk_idx
  on public.harvests (batch_pk);
create index if not exists harvests_harvest_date_idx
  on public.harvests (harvest_date desc);
create index if not exists harvests_strain_harvest_date_idx
  on public.harvests (strain, harvest_date desc);

alter table public.harvests enable row level security;
revoke all on table public.harvests from public, anon;
grant select, insert, update, delete on table public.harvests to authenticated;
grant usage, select on sequence public.harvests_id_seq to authenticated;

drop policy if exists garnish_owner_all_harvests on public.harvests;
create policy garnish_owner_all_harvests
  on public.harvests
  for all
  to authenticated
  using (auth.uid() = '4ece3fb4-cdf6-48a8-abdf-9d1c8101ab5d'::uuid)
  with check (auth.uid() = '4ece3fb4-cdf6-48a8-abdf-9d1c8101ab5d'::uuid);

commit;
